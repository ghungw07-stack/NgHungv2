import { registerAdminCommands } from "../modules/admins/commands.js";
import { registerOperationCommands } from "../modules/operations/commands.js";
import { registerBulkGroupCommands } from "../modules/bulk-groups/commands.js";

export function registerRuntimeCommands(registry, dependencies) {
  const d = dependencies;
  registerSystemCommands(registry, { startedAt: d.startedAt, scheduler: d.scheduler, runtimeStats: d.runtimeStats });
  registerBotManagerCommands(registry, { fleet: d.fleet, identity: d.identity });
  registerGroupSettingsCommands(registry, { repository: d.groupSettings });
  registerGroupCommands(registry, { groups: d.groups, client: d.client });
  registerModerationCommands(registry, { repository: d.groupSettings });
  registerMediaCommands(registry, { media: d.media, client: d.client });
  registerUtilityCommands(registry, { client: d.client });
  registerContentCommands(registry, d.content);
  registerEconomyCommands(registry, { players: d.players });
  registerBigGameCommands(registry, { engine: d.bigGames, players: d.players });
  registerMiniGameCommands(registry, { sessions: d.gameSessions, players: d.players });
  registerXiDachCommand(registry, { game: d.xiDach, sessions: d.gameSessions, players: d.players });
  registerCaroCommand(registry, { sessions: d.gameSessions });
  registerAiCommands(registry, { gateway: d.ai, conversations: d.aiConversations, botId: d.botId });
  registerAutoJoinCommands(registry, { settings: d.groupSettings });
  registerGroupEventCommands(registry, { settings: d.groupSettings });
  registerSourceUpdateCommand(registry, { updater: d.sourceUpdater, identity: d.identity });
  registerCommandManagerCommands(registry, { settings: d.groupSettings });
  registerMessageActionCommands(registry, { client: d.client, groups: d.groups });
  registerPaymentCommands(registry, { qr: d.paymentQr, client: d.client, identity: d.identity });
  registerQrCommands(registry, { qr: d.qr, client: d.client });
  registerReminderCommands(registry, { reminders: d.reminders });
  registerBasicToolCommands(registry);
  registerContactCommands(registry, { client: d.client, qr: d.qr });
  registerConversationCommands(registry, { client: d.client });
  registerStickerCommands(registry, { client: d.client });
  registerEngagementCommands(registry, { archive: d.messageArchive });
  registerBankingCommands(registry, { accounts: d.bankAccounts, client: d.client, paymentQr: d.paymentQr });
  registerAccountCommands(registry, { client: d.client });
  registerAdminCommands(registry, { store: d.adminStore, botId: d.botId });
  registerOperationCommands(registry, { settings: d.groupSettings, adminStore: d.adminStore, botId: d.botId });
  registerBulkGroupCommands(registry, { client: d.client, groups: d.groups });
  return registry;
}
